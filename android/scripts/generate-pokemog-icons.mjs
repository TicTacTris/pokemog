// Run with node scripts/generate-pokemog-icons.mjs [--check] [--preview].
// Kotlin is the source of truth; no downloaded artwork or third-party dependencies.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import assert from 'node:assert/strict';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('app/src/main/java/dev/pokemog/android/PixelPokeball.kt', root), 'utf8');
const rows = [...source.matchAll(/"([.H#RLWC]{16})"/g)].map(m => m[1]);
const palette = Object.fromEntries([...source.matchAll(/'(.)' to 0xFF([0-9A-F]{6})\.toInt\(\)/g)].map(m => [m[1], `#${m[2]}`]));
assert.equal(rows.length, 16);
assert.equal(Object.keys(palette).length, 6);
for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
  const pixel = rows[y][x];
  assert.ok(pixel === '.' || palette[pixel]);
  assert.equal(pixel === '.', rows[y][15 - x] === '.');
  if (pixel !== '.') {
    // Every occupied pixel corner stays inside the adaptive mask's 66dp safe circle.
    for (const dx of [0, 1]) for (const dy of [0, 1]) {
      assert.ok(Math.hypot((x + dx - 8) * 4, (y + dy - 8) * 4) <= 33);
    }
  }
}

function vector(size, adaptive = false, monochrome = false) {
  const paths = [];
  for (const [key, color] of Object.entries(palette)) {
    if (monochrome && key !== '#') continue;
    let path = '';
    for (let y = 0; y < 16; y++) for (let x = 0; x < 16;) {
      if (rows[y][x] !== key) { x++; continue; }
      const start = x++;
      while (x < 16 && rows[y][x] === key) x++;
      path += `M${start},${y}h${x - start}v1h-${x - start}z`;
    }
    paths.push(`    <path android:fillColor="${monochrome ? '#FFFFFF' : color}" android:pathData="${path}" />`);
  }
  const viewport = adaptive ? 108 : 16;
  return `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${size}dp" android:height="${size}dp" android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">\n` +
    (adaptive ? '    <group android:translateX="22" android:translateY="22" android:scaleX="4" android:scaleY="4">\n' : '') +
    paths.join('\n') + '\n' + (adaptive ? '    </group>\n' : '') + '</vector>';
}

function adaptive(themed) {
  return `<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
    `    <background><shape android:shape="rectangle"><solid android:color="${palette.H}" /></shape></background>\n` +
    `    <foreground>\n${vector(108, true)}\n    </foreground>\n` +
    (themed ? `    <monochrome>\n${vector(108, true, true)}\n    </monochrome>\n` : '') +
    '</adaptive-icon>';
}

const outputs = {
  'drawable/ic_launcher.xml': vector(48),
  'drawable/ic_pokeball.xml': vector(48),
  'drawable/ic_notification.xml': vector(24, false, true),
  'mipmap-anydpi-v26/ic_launcher.xml': adaptive(false),
  'mipmap-anydpi-v33/ic_launcher.xml': adaptive(true),
};
for (const [path, xml] of Object.entries(outputs)) {
  const url = new URL(`app/src/main/res/${path}`, root);
  const content = '<!-- Generated by scripts/generate-pokemog-icons.mjs; edit PixelPokeball.kt. -->\n' + xml + '\n';
  if (process.argv.includes('--check')) assert.equal(readFileSync(url, 'utf8'), content, path);
  else {
    mkdirSync(new URL('./', url), { recursive: true });
    writeFileSync(url, content);
  }
}
console.log(`Validated 16x16 grid, palette, adaptive safe circle and ${Object.keys(outputs).length} resources.`);

if (process.argv.includes('--preview')) {
  // Dependency-free PNG contact sheet: light, dark, adaptive, notification, themed.
  const width = 960, height = 192;
  const raw = Buffer.alloc(height * (width * 4 + 1));
  const backgrounds = ['#FFF2D9', '#19171D', '#FFF2D9', '#45414B', '#DCD6E8'];
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    const panel = Math.floor(x / 192), localX = x % 192;
    const scale = panel === 2 || panel === 4 ? 7 : 10;
    const start = (192 - 16 * scale) / 2;
    const gx = Math.floor((localX - start) / scale), gy = Math.floor((y - start) / scale);
    const pixel = gx >= 0 && gx < 16 && gy >= 0 && gy < 16 ? rows[gy][gx] : '.';
    let color = backgrounds[panel];
    if (panel < 3 && palette[pixel]) color = palette[pixel];
    if (panel >= 3 && pixel === '#') color = panel === 3 ? '#FFFFFF' : '#423650';
    const offset = y * (width * 4 + 1) + 1 + x * 4;
    raw[offset] = parseInt(color.slice(1, 3), 16);
    raw[offset + 1] = parseInt(color.slice(3, 5), 16);
    raw[offset + 2] = parseInt(color.slice(5, 7), 16);
    raw[offset + 3] = 255;
  }
  function chunk(type, data) {
    const bytes = Buffer.concat([Buffer.from(type), data]);
    let crc = 0xFFFFFFFF;
    for (const byte of bytes) {
      crc ^= byte;
      for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xEDB88320 : 0);
    }
    const result = Buffer.alloc(data.length + 12);
    result.writeUInt32BE(data.length);
    bytes.copy(result, 4);
    result.writeUInt32BE((crc ^ 0xFFFFFFFF) >>> 0, result.length - 4);
    return result;
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width); header.writeUInt32BE(height, 4);
  header[8] = 8; header[9] = 6;
  const output = '/tmp/opencode/pokemog-icons-preview.png';
  writeFileSync(output, Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', header), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0)),
  ]));
  console.log(`Preview: ${output}`);
}
